CREATE DATABASE IF NOT EXISTS careerai_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE careerai_db;
CREATE TABLE IF NOT EXISTS users (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 name VARCHAR(120) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE,
 password VARCHAR(255) NOT NULL,
 role ENUM('ADMIN','CANDIDATE') NOT NULL DEFAULT 'CANDIDATE',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS cv_analyses (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 user_id BIGINT NOT NULL,
 file_name VARCHAR(255) NOT NULL,
 score DECIMAL(5,2) NULL,
 result_json LONGTEXT NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_cv_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
